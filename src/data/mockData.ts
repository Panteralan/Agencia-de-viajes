export function formatPrice(priceUSD: number, currency: Currency): string {
  const conf = CURRENCY_RATES[currency] || CURRENCY_RATES.ARS;
  const localVal = Math.round(priceUSD * conf.rate);
  return `${conf.symbol} ${localVal.toLocaleString('es-AR')}`;
}

